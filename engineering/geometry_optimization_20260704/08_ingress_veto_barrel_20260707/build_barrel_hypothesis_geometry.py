def now_utc() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def rel(path: Path | str) -> str:
    p = Path(path)
    try:
        return p.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return str(path)


def allowed_name(name: str) -> bool:
    return name in ALLOWLIST_EXACT or any(name.startswith(prefix) for prefix in ALLOWLIST_PREFIXES)


def denied_name(name: str) -> bool:
    return any(name.startswith(prefix) for prefix in DENYLIST_PREFIXES)


def volume_name_from_line(line: str) -> str | None:
    if line.startswith("Volume "):
        return line.split(None, 1)[1].strip()
    return None


def copy_name_from_line(line: str) -> tuple[str, str] | None:
    match = re.match(r"^([A-Za-z0-9_]+)\.Copy\s+([A-Za-z0-9_]+)\s*$", line.strip())
    if not match:
        return None
    return match.group(1), match.group(2)


def collect_block(lines: list[str], start: int) -> tuple[list[str], int]:
    block = [lines[start]]
    i = start + 1
    while i < len(lines):
        block.append(lines[i])
        if lines[i].strip() == "":
            i += 1
            break
        i += 1
    return block, i


def shape_allowed(name: str) -> bool:
    return name.startswith(("CsI_", "TES_", "TP_", "NF2_OuterSupport_", "Hyp_"))


def line_has_deny_token(line: str) -> bool:
    return any(token in line for token in DENYLIST_PREFIXES)


def property_prefix(line: str) -> str | None:
    match = re.match(r"^([A-Za-z0-9_]+)\.", line.strip())
    return match.group(1) if match else None


def filter_geo() -> dict[str, Any]:
    lines = SOURCE_GEO.read_text(encoding="utf-8", errors="ignore").splitlines()
    out: list[str] = [
        f"// {LABEL}",
        "// Generated by build_barrel_hypothesis_geometry.py",
        f"Include {OUT_MATERIALS.name}",
        "",
        "Name HypBarrelW_TES_CsI_ExternalSupport",
        "Version 1",
        "",
        "Volume WorldVolume",
        "WorldVolume.Visibility 0",
        "WorldVolume.Material Vacuum",
        "WorldVolume.Shape BRIK 1000 1000 1000",
        "WorldVolume.Mother 0",
        "",
        "Volume InstrumentFrame",
        "InstrumentFrame.Visibility 0",
        "InstrumentFrame.Material Vacuum",
        "InstrumentFrame.Shape BRIK 80 80 80",
        "InstrumentFrame.Position 0 0 0",
        "InstrumentFrame.Rotation 0 45 0",
        "InstrumentFrame.Mother WorldVolume",
        "",
    ]
    kept: list[str] = ["WorldVolume", "InstrumentFrame"]
    removed: list[str] = []
    denied_removed: list[str] = []
    for line in lines:
        if line.startswith("Include Intro_"):
            continue
        vol = volume_name_from_line(line)
        copy = copy_name_from_line(line)
        if vol is not None:
            if vol in ALLOWLIST_EXACT:
                # The generated intro above defines these containers.
                kept.append(vol)
            elif allowed_name(vol):
                out.append(line)
                kept.append(vol)
            else:
                removed.append(vol)
                if denied_name(vol):
                    denied_removed.append(vol)
            continue
        if copy is not None:
            base, inst = copy
            if allowed_name(base) or allowed_name(inst):
                out.append(line)
                kept.append(inst)
            else:
                removed.append(inst)
                if denied_name(inst) or denied_name(base):
                    denied_removed.append(inst)
            continue
        if not line.strip():
            out.append(line)
            continue
        if line_has_deny_token(line):
            continue
        if line.startswith("// Volume "):
            name = line.split("Volume ", 1)[1].split(";", 1)[0].strip()
            if allowed_name(name):
                out.append(line)
            continue
        if line.startswith("//"):
            # Drop old construction comments that are unrelated to retained
            # volumes; they otherwise obscure the allowlist audit.
            if any(prefix in line for prefix in ("TES_", "TP_", "CsI_", "NF2_OuterSupport_")):
                out.append(line)
            continue
        if line.startswith("Shape "):
            parts = line.split()
            shape_name = parts[2] if len(parts) >= 3 and parts[1] != "Subtraction" else (parts[2] if len(parts) >= 3 else "")
            if shape_allowed(shape_name):
                out.append(line)
            continue
        if line.startswith("Orientation "):
            parts = line.split()
            if len(parts) >= 2 and shape_allowed(parts[1]):
                out.append(line)
            continue
        prefix = property_prefix(line)
        if prefix is not None:
            if allowed_name(prefix) or shape_allowed(prefix):
                out.append(line)
            continue
        # Keep other neutral MEGAlib syntax only when it is not tied to a
        # removed structure.
        out.append(line)

    out.extend(barrel_geo_lines())
    OUT_GEO.write_text("\n".join(out).rstrip() + "\n", encoding="utf-8")
    return {
        "kept_names": sorted(set(kept)),
        "removed_names": sorted(set(removed)),
        "denylist_removed": sorted(set(denied_removed)),
        "kept_counts_by_prefix": count_by_prefix(kept),
        "removed_counts_by_prefix": count_by_prefix(removed),
    }


def count_by_prefix(names: list[str]) -> dict[str, int]:
    prefixes = {
        "TES": "TES_",
        "TP": "TP_",
        "CsI": "CsI_",
        "NF2_OuterSupport": "NF2_OuterSupport_",
        "GeoOpt": "GeoOpt_",
        "CryostatWindowShell": "Vacuum_Jacket_|Shield_|Still_Shield_|Plate_|Win_",
        "DRCold": "DR_|ColdPlate_|Cu_ColdFinger_|Cu_MXC_|Cu_SubstrateSupport_|Si_Substrate_",
    }
    out: dict[str, int] = {}
    for label, prefix_expr in prefixes.items():
        parts = prefix_expr.split("|")
        out[label] = sum(1 for name in names if any(name.startswith(part) for part in parts))
    out["total"] = len(set(names))
    return out


