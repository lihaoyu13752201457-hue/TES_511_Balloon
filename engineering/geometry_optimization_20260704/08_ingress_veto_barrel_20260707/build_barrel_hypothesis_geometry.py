def main() -> int:
    GEOM_DIR.mkdir(parents=True, exist_ok=True)
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    write_materials()
    geo_report = filter_geo()
    det_report = filter_det()
    write_setup()
    write_figures()

    side_volume_cm3 = math.pi * (BARREL["outer_radius_cm"] ** 2 - BARREL["inner_radius_cm"] ** 2) * (
        BARREL["side_z_max_cm"] - BARREL["side_z_min_cm"]
    )
    cap_volume_cm3 = math.pi * BARREL["outer_radius_cm"] ** 2 * BARREL["cap_thickness_cm"]
    al_volume_cm3 = (
        2
        * BARREL["window_al_half_thickness_cm"]
        * 2
        * BARREL["window_half_y_cm"]
        * 2
        * BARREL["window_half_z_cm"]
    )
    manifest = {
        "status": "PASS_BUILD_HYPOTHESIS_GEOMETRY_NOT_TRANSPORT_VALIDATED",
        "generated_at_utc": now_utc(),
        "source_geometry": rel(SOURCE_GEO),
        "source_detector": rel(SOURCE_DET),
        "generated_geometry_setup": rel(OUT_SETUP),
        "generated_geometry": rel(OUT_GEO),
        "generated_detector": rel(OUT_DET),
        "generated_materials": rel(OUT_MATERIALS),
        "figures": {"detail_png": rel(OUT_DETAIL_PNG), "detail_svg": rel(OUT_DETAIL_SVG), "wrl": rel(OUT_WRL)},
        "barrel": {
            **BARREL,
            "side_wall_volume_cm3": side_volume_cm3,
            "one_cap_volume_cm3": cap_volume_cm3,
            "total_w_volume_cm3": side_volume_cm3 + 2 * cap_volume_cm3,
            "total_w_mass_kg": (side_volume_cm3 + 2 * cap_volume_cm3) * 19.3 / 1000.0,
            "thin_al_window_volume_cm3": al_volume_cm3,
            "thin_al_window_mass_g": al_volume_cm3 * 2.7,
            "active_veto_status": "passive only; not counted as active veto energy",
        },
        "allowlist_prefixes": list(ALLOWLIST_PREFIXES),
        "allowlist_exact": sorted(ALLOWLIST_EXACT),
        "denylist_prefixes": list(DENYLIST_PREFIXES),
        "geometry_filter_report": geo_report,
        "detector_filter_report": det_report,
        "review_notes": [
            "Retains TES and CsI position/shape definitions by copying their current geometry blocks.",
            "Retains NF2_OuterSupport_* as explicit external support volumes.",
            "Removes current GeoOpt plastic/BPE/W add-ons to isolate passive barrel hypothesis.",
            "Does not retain internal cryostat/passive shell/window/DR/coldplate stacks.",
            "Passive W/Al barrel deposits must not be included in active anticoincidence; CsI is the retained active veto.",
        ],
    }
    OUT_MANIFEST.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(json.dumps({"status": manifest["status"], "setup": rel(OUT_SETUP), "manifest": rel(OUT_MANIFEST)}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
