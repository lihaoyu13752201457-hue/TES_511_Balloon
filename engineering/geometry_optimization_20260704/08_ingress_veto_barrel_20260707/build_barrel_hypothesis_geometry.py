def filter_det() -> dict[str, Any]:
    lines = SOURCE_DET.read_text(encoding="utf-8", errors="ignore").splitlines()
    out = [f"// {LABEL} detector map", "// Retains TES MDCalorimeters and CsI scintillator active veto only.", ""]
    kept: list[str] = []
    removed: list[str] = []
    i = 0
    while i < len(lines):
        line = lines[i]
        if not (line.startswith("MDCalorimeter ") or line.startswith("Scintillator ")):
            i += 1
            continue
        block, j = collect_block(lines, i)
        name = line.split(None, 1)[1].strip()
        text = "\n".join(block)
        if line.startswith("MDCalorimeter ") and name in {"D1", "D2", "D3", "D4", "D5", "D6"}:
            out.extend(block)
            kept.append(name)
        elif line.startswith("Scintillator ") and ".SensitiveVolume CsI_" in text:
            out.extend(block)
            kept.append(name)
        else:
            removed.append(name)
        i = j
    OUT_DET.write_text("\n".join(out).rstrip() + "\n", encoding="utf-8")
    return {"kept_detector_entries": kept, "removed_detector_entries": removed}


